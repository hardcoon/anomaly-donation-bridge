-- Model the engine's process-wide INI cache. The direct reader must never use
-- this API: a second ini_file(path) still returns the first revision's data.
ini_file = function(path)
    assert(path == "plugins\\anomaly_donation_bridge_safe_zone.ltx")
    native_reads = native_reads + 1
    if not native_data then
        native_data = {}
        for section, values in pairs(data) do
            native_data[section] = {}; for key, value in pairs(values) do native_data[section][key] = value end
        end
    end
    return {
        section_exist = function(_, section) return native_data[section] ~= nil end,
        line_exist = function(_, section, key) return native_data[section] ~= nil and native_data[section][key] ~= nil end,
        r_string = function(_, section, key) return native_data[section][key] end
    }
end
io.open = function(path, mode)
    assert(path == config_path and mode == "rb")
    direct_reads = direct_reads + 1
    local file = real_open(path, mode)
    if not file then return nil end
    return { read = function(_, size) return file:read(size) end,
        close = function() closed_reads = closed_reads + 1; return file:close() end }
end
local function write_config()
    if not present then os.remove(config_path); return end
    local file = assert(real_open(config_path, "wb"))
    if raw_config then file:write(raw_config) else
        file:write("; Generated by Anomaly Donation Bridge.\r\n")
        for section, values in pairs(data) do
            file:write("\r\n[", section, "]\r\n")
            for key, value in pairs(values) do file:write(key, " = ", value, "\r\n") end
        end
    end
    assert(file:close())
end
