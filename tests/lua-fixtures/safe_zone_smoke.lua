        command = { safe_zone_required = guarded == true, safe_zone_revision = revision, safe_zone_source_handler_id = source }
    }, {}, function() before = before + 1; return true end)
end
local function expect(action, guarded, status, reason)
    local old_execute, old_before, old_checked = executed, before, checked
    local actual, actual_reason = run(action, guarded)
    assert(actual == status, tostring(actual) .. " != " .. status .. ": " .. tostring(actual_reason))
    if reason then assert(actual_reason == reason, tostring(actual_reason) .. " != " .. reason) end
    if status ~= "executed" then
        assert(executed == old_execute and before == old_before and checked == old_checked,
            "Blocked command ran a handler, a precondition or a pre-effect save")
    end
end
