using System.Text;
using System.Security.Cryptography;
using AnomalyDonationBridge.Core;
using AnomalyDonationBridge.Persistence;

namespace AnomalyDonationBridge.App.Services;

internal static class SafeZoneConfig
{
    public const string Capability = "safe_zone_v1";
    public const string RelativePath = "gamedata\\configs\\plugins\\anomaly_donation_bridge_safe_zone.ltx";
    private static readonly SemaphoreSlim WriteGate = new(1, 1);
    internal static string Revision(SafeZoneSettings settings) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(Serialize(settings)))).ToLowerInvariant();

    internal static string Serialize(SafeZoneSettings settings)
    {
        var normalized = SafeZoneSettings.Normalize(settings);
        var builder = new StringBuilder("; Generated by Anomaly Donation Bridge. Configure Safe Zone in the application.\n");
        builder.AppendLine("[safe_zone]").AppendLine("schema = 1")
            .Append("enabled = ").AppendLine(normalized.Enabled ? "true" : "false")
            .Append("blocked_action = ").AppendLine(normalized.BlockedAction == SafeZoneBlockedAction.Wait ? "wait" : "skip");
        foreach (var rule in normalized.Rules.OrderBy(rule => rule.LevelName, StringComparer.Ordinal))
        {
            builder.AppendLine().Append("[level_").Append(rule.LevelName).AppendLine("]")
                .Append("mode = ").AppendLine(rule.BlockAll ? "all" : "selected");
            builder.Append("[level_").Append(rule.LevelName).AppendLine("_effects]");
            foreach (var handler in rule.HandlerIds.OrderBy(id => id, StringComparer.Ordinal))
                builder.Append(handler).AppendLine(" = true");
        }
        return builder.ToString();
    }

    public static async Task WriteAsync(string gamePath, SafeZoneSettings settings,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(gamePath) || !Directory.Exists(gamePath)) return;
        var normalized = SafeZoneSettings.Normalize(settings);
        var content = Serialize(normalized) + "\n[safe_zone_revision]\nvalue = " + Revision(normalized) + "\n";
        var path = Path.Combine(Path.GetFullPath(gamePath), RelativePath);
        await WriteGate.WaitAsync(cancellationToken).ConfigureAwait(false);
        string? temporary = null;
        try
        {
            if (File.Exists(path) && await File.ReadAllTextAsync(path, cancellationToken).ConfigureAwait(false) == content) return;
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            temporary = path + "." + Guid.NewGuid().ToString("N") + ".tmp";
            await File.WriteAllTextAsync(temporary, content, new UTF8Encoding(false), cancellationToken).ConfigureAwait(false);
            File.Move(temporary, path, true);
        }
        finally
        {
            if (temporary is not null && File.Exists(temporary)) File.Delete(temporary);
            WriteGate.Release();
        }
    }

    internal static CatalogCommandValidationResult Prepare(GameCommand command, CapabilitySet capabilities,
        SafeZoneSettings settings, bool synchronized)
    {
        if (ActorBoostRecovery.IsResetCommand(command))
        {
            command.RequireSafeZoneCheck = false;
            command.SafeZoneRevision = string.Empty;
            return CatalogCommandValidationResult.Valid;
        }
        command.RequireSafeZoneCheck = settings.Enabled;
        command.SafeZoneRevision = settings.Enabled ? Revision(settings) : string.Empty;
        if (!settings.Enabled) return CatalogCommandValidationResult.Valid;
        if (!synchronized)
            return CatalogCommandValidationResult.Awaiting("Безопасная зона: правила ещё не переданы игре.");
        return capabilities.SupportsCapability(Capability)
            ? CatalogCommandValidationResult.Valid
            : CatalogCommandValidationResult.Awaiting("Безопасная зона: обновите аддон и полностью перезапустите игру.");
    }
}
