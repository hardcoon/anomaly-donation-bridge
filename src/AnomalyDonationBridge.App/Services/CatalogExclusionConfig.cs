using System.Text;
using AnomalyDonationBridge.Persistence;

namespace AnomalyDonationBridge.App.Services;

internal static class CatalogExclusionConfig
{
    public const string RelativePath = "gamedata\\configs\\plugins\\anomaly_donation_bridge_exclusions.ltx";

    public static async Task WriteAsync(
        string gamePath,
        IEnumerable<CatalogExclusion> exclusions,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(gamePath) || !Directory.Exists(gamePath)) return;
        var path = Path.Combine(Path.GetFullPath(gamePath), RelativePath);
        var directory = Path.GetDirectoryName(path)!;
        Directory.CreateDirectory(directory);
        var normalized = SettingsNormalizer.NormalizeCatalogExclusions(exclusions);
        var builder = new StringBuilder();
        builder.AppendLine("; Generated by Anomaly Donation Bridge. Edit exclusions in the application.");
        builder.AppendLine("[excluded_sections]");
        foreach (var entry in normalized.Select(entry => entry.SectionId)
                     .Distinct(StringComparer.OrdinalIgnoreCase)
                     .OrderBy(value => value, StringComparer.OrdinalIgnoreCase))
            builder.Append(entry).AppendLine(" = true");

        var temporary = path + ".tmp";
        await File.WriteAllTextAsync(temporary, builder.ToString(), new UTF8Encoding(false), cancellationToken)
            .ConfigureAwait(false);
        File.Move(temporary, path, true);
    }
}
